<li><b>Ранжирование.</b> Когда человек вводит запрос, поисковик выбирает из индекса подходящие страницы и упорядочивает их по сотням факторов: насколько страница отвечает на запрос, насколько удобна, насколько ей доверяют пользователи и другие сайты.</li>
