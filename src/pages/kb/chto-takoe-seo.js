<h2 id="opredelenie">Что такое SEO</h2>
<p><b>SEO</b> (англ. Search Engine Optimization — «оптимизация под поисковые системы») — комплекс работ с сайтом, после которых поисковые системы показывают его страницы выше в бесплатной (органической) выдаче по нужным запросам.</p>
<p>Часто встречаются два близких термина:</p>
<ul>
<li><b>SEO-оптимизация</b> — работа внутри сайта: структура, техническое состояние, тексты, мета-теги, скорость, удобство.</li>
